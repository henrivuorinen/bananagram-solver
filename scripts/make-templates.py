"""Renders the letter templates used to recognise tiles (src/ocr/templates.ts).

The output is committed, so this only needs re-running to change the font or template size.
Requires Python 3 with Pillow:  python3 scripts/make-templates.py

Font: Arimo (SIL Open Font License), a plain sans-serif close to the Bananagrams tile font.
"""
import base64
import io
import os
import urllib.request

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_URL = 'https://github.com/google/fonts/raw/main/ofl/arimo/Arimo%5Bwght%5D.ttf'
FONT_PATH = os.path.join(ROOT, 'scripts', '.cache', 'Arimo.ttf')
OUT = os.path.join(ROOT, 'src', 'ocr', 'templates.ts')

LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZÅÄÖ'
WEIGHTS = ['Regular', 'Bold']  # tiles vary in print weight and photos blur strokes
GRID = 40  # must match TEMPLATE_GRID in classify.ts
FIT = 32   # long side of the letter inside the grid; must match TEMPLATE_FIT


def font(weight):
    if not os.path.exists(FONT_PATH):
        os.makedirs(os.path.dirname(FONT_PATH), exist_ok=True)
        urllib.request.urlretrieve(FONT_URL, FONT_PATH)
    f = ImageFont.truetype(FONT_PATH, 160)
    f.set_variation_by_name(weight)
    return f


def render(ch, f):
    """Letter scaled so its long side is FIT px, centred in a GRID×GRID square, as a bitmask."""
    im = Image.new('L', (260, 260), 255)
    ImageDraw.Draw(im).text((130, 130), ch, font=f, fill=0, anchor='mm')
    bbox = Image.eval(im, lambda v: 255 - v).getbbox()
    crop = im.crop(bbox)
    k = FIT / max(crop.size)
    crop = crop.resize((max(1, round(crop.width * k)), max(1, round(crop.height * k))), Image.BILINEAR)
    grid = Image.new('L', (GRID, GRID), 255)
    grid.paste(crop, ((GRID - crop.width) // 2, (GRID - crop.height) // 2))
    bits = bytearray(GRID * GRID // 8)
    for i, v in enumerate(grid.getdata()):
        if v < 128:
            bits[i // 8] |= 1 << (i % 8)
    return base64.b64encode(bytes(bits)).decode()


def main():
    fonts = [font(w) for w in WEIGHTS]
    lines = [
        '// Generated by scripts/make-templates.py. Do not edit by hand.',
        '// Letter shapes rendered from Arimo (SIL Open Font License), one bitmask per font weight:',
        f'// {GRID}×{GRID} pixels, letter fitted to {FIT} px on its long side, 1 bit per pixel, base64.',
        'export const TEMPLATES: Record<string, string[]> = {',
    ]
    for ch in LETTERS:
        lines.append(f"  '{ch}': [{', '.join(repr(render(ch, f)) for f in fonts)}],")
    lines.append('};')
    with io.open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines) + '\n')
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
